import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

// Apply to the supplied, pinned upstream source, never to an already patched
// bundle. Re-running postinstall is safe and works without network access.
const originalSha256 = "fef0c2fc442d24fdef5c7c7cc37d5da2314407640fe11ab1bfe347c723dff19b";
const digest = bytes => createHash("sha256").update(bytes).digest("hex");
export function buildPiperLoader(source) {
  assert.equal(digest(source), originalSha256, "Исходный Piper изменился: проверьте совместимость патча перед обновлением.");
  const replace = (before, after) => {
    assert.equal(source.split(before).length, 2, "Точка применения патча Piper изменилась.");
    source = source.replace(before, after);
  };
  replace("return new Uint8Array(wasmBinary)", "return wasmBinary");
  replace(".then(binary=>WebAssembly.instantiate(binary,imports)).then(instance=>instance)",
    ".then(binary=>{var compiled=bridgeWasmModules.get(binary);if(!compiled){compiled=WebAssembly.compile(binary);bridgeWasmModules.set(binary,compiled);compiled.catch(()=>bridgeWasmModules.delete(binary))}return compiled.then(module=>WebAssembly.instantiate(module,imports)).then(instance=>({instance}))})");
  const start = source.indexOf("function callMain(args=[])");
  const end = source.indexOf("function run(args=arguments_)", start);
  assert.ok(start >= 0 && end > start, "Не найдена обёртка CLI Piper.");
  source = source.slice(0, start) + 'var bridgeArgv=0;function callMain(args=[]){var entryFunction=_main;args=[thisProgram,...args];var argc=args.length;var total=args.reduce((n,arg)=>n+lengthBytesUTF8(arg)+1,0);if(argc>16||total>16000)throw new Error("Phonemizer arguments too long");if(!bridgeArgv)bridgeArgv=stackAlloc(16384);var argv=bridgeArgv;var argv_ptr=argv;var str_ptr=argv+128;args.forEach(arg=>{var bytes=lengthBytesUTF8(arg)+1;stringToUTF8(arg,str_ptr,bytes);HEAPU32[argv_ptr>>2]=str_ptr;str_ptr+=bytes;argv_ptr+=4});HEAPU32[argv_ptr>>2]=0;try{var ret=entryFunction(argc,argv);exitJS(ret,true);return ret}catch(e){return handleException(e)}}' + source.slice(end);
  return '// @diffusionstudio/piper-wasm 1.0.0, adapted by Bridge 2026-10-26.\n// Generated by scripts/prepare-vendor.mjs: ESM, bounded argv, shared WASM compilation.\n// Original source and build notes: ../../licenses/sources/.\nconst bridgeWasmModules = new WeakMap();\n' + source + '\nexport { createPiperPhonemize };\n';
}

export async function prepareVendor({ check = false, root = new URL("../extension/", import.meta.url) } = {}) {
  const source = await readFile(new URL("licenses/sources/piper_phonemize.original.js", root), "utf8");
  const output = buildPiperLoader(source), bytes = Buffer.from(output);
  const lock = JSON.parse(await readFile(new URL("voices/assets.lock.json", root), "utf8"));
  const record = lock.files.find(file => file.path === "vendor/piper/phonemize.mjs");
  assert.equal(record?.sha256, digest(bytes), "Патч Piper не совпал с assets.lock.json.");
  assert.equal(record.bytes, bytes.length);
  const target = new URL(record.path, root);
  let existing;
  try { existing = await readFile(target, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (existing === output) return;
  assert.ok(!check, "Piper не подготовлен. Выполните npm run vendor:prepare.");
  await mkdir(new URL("vendor/piper/", root), { recursive: true });
  await writeFile(target, output);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await prepareVendor({ check: process.argv.includes("--check") });
  console.log("Локальный Piper: воспроизводимый патч и контрольная сумма OK.");
}
